-- `packages/mods/pkg-selftest/mod.lua` —— **pack 自测的消费夹具**，不是产品 Mod。
--
-- M2.5 起本夹具只剩「装得上的壳」：一线内容包（entity / codec / quest / dialogue /
-- procgen / role-skill）随包层退役一起删除，包自测面因此收敛为一件事实——
-- **一个不声明任何包的 Mod 仍然装得上**。被测面就是同目录的 `pack.json`。
--
-- 它被两处消费：
--   ① `examples/selftest --mod packages/mods/pkg-selftest`——harness 与 `tests/`
--      的可执行底座（`tests/smoke.lua` 是这里的唯一用例）；
--   ② `crates/ygg-lint/tests/rules.rs` 的 golden（`GOLDEN_MOD`）——零诊断回归锚，
--      所以本文件必须保持 lint 干净。
--
-- 它不写 KV、不注册 handler、不 require 任何 `pkg.*`：包层不在场时一条
-- `require("pkg.…")` 会让 `examples/selftest` 在入口就失败，而入口失败与
-- 「包自测跑了几条」是两件事——夹具不做后者的替代。
